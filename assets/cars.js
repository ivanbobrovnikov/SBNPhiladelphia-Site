/* =========================================================
   SBN Studio — real vehicle photos + pixel masks.
   assets/img/cars/<type>.jpg            1600 x 615 photo (free under the Unsplash License)
   assets/img/cars/<type>-front.png      front side-window mask
   assets/img/cars/<type>-rear.png       rear side-window mask
   assets/img/cars/<type>-paint.png      body mask (where PPF film can go)
   Masks are generated by tools/make_masks.py from the outlines in tools/car-masks.json.
   dir: which way the car faces. zones: where each PPF package ends, in photo pixels
   ([x, y] for the bumper: film below y and in front of x).
   ========================================================= */
(function () {
  const W = 1600, H = 615;
  const TYPES = {
    sedan:  { label: "Sedan",      model: "BMW 3 Series (E30)",    dir: "left",  zones: { bumper: [165, 365], partial: 330, full: 520 } },
    coupe:  { label: "Coupe",      model: "BMW 4 Series",          dir: "right", zones: { bumper: [1460, 250], partial: 1290, full: 1040 } },
    sports: { label: "Sports car", model: "Lamborghini Aventador", dir: "left",  zones: { bumper: [190, 290], partial: 330, full: 470 } },
    suv:    { label: "SUV",        model: "Cadillac Lyriq",        dir: "right", zones: { bumper: [1470, 290], partial: 1280, full: 1060 }, privacy: true },
    truck:  { label: "Truck",      model: "GMC Sierra",            dir: "left",  zones: { bumper: [115, 200], partial: 300, full: 470 }, privacy: true },
  };

  const base = ((document.querySelector('script[src*="cars.js"]') || {}).src || "").replace(/cars\.js.*$/, "img/cars/");
  const url = f => base + f;
  const mask = f => `-webkit-mask-image:url('${url(f)}');mask-image:url('${url(f)}')`;

  function render(type) {
    const c = TYPES[type] || TYPES.sedan;
    return `<div class="car-photo" data-type="${type}">
  <img src="${url(type + ".jpg")}" alt="${c.model} side view" width="${W}" height="${H}"/>
  <div class="tint-layer tint-front" style="${mask(type + "-front.png")}"></div>
  <div class="tint-layer tint-rear" style="${mask(type + "-rear.png")}"></div>
  <div class="glass-sheen" style="-webkit-mask-image:url('${url(type + "-front.png")}'),url('${url(type + "-rear.png")}');mask-image:url('${url(type + "-front.png")}'),url('${url(type + "-rear.png")}')"></div>
  <div class="ppf-layer" style="${mask(type + "-paint.png")}"></div>
</div>`;
  }

  /* A film passes VLT% of the light, so the glass gets black at (1 - VLT) opacity. */
  function setTint(el, front, rear) {
    const a = v => (v ? 1 - v / 100 : 0);
    el.querySelector(".tint-front").style.opacity = a(front);
    el.querySelector(".tint-rear").style.opacity = a(rear);
    el.querySelector(".glass-sheen").style.opacity = (0.04 + 0.16 * Math.max(a(front), a(rear))).toFixed(2);
  }

  window.SBNCars = { types: TYPES, render, setTint, W, H };
})();
